\getenv app_password POSTGRES_APP_PASSWORD
CREATE SCHEMA IF NOT EXISTS sgaec;
CREATE ROLE sgaec_app WITH LOGIN PASSWORD :'app_password'
  NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
GRANT USAGE ON SCHEMA sgaec TO sgaec_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA sgaec
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO sgaec_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA sgaec
  GRANT USAGE, SELECT ON SEQUENCES TO sgaec_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA sgaec
  GRANT USAGE ON TYPES TO sgaec_app;
